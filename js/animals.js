const spiral = (cx, cy, R, turns) => {
  const pts = [], n = Math.round(turns * 12);
  for (let i = 0; i <= n; i++) { const a = i * Math.PI / 6, k = R * (1 - i / (n + 2)); pts.push([cx + Math.cos(a) * k, cy + Math.sin(a) * k]); }
  return smooth(pts);
};

